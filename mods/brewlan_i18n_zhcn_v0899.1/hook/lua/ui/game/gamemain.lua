local _oldLOC = rawget(_G, 'LOC')
if _oldLOC and type(_oldLOC) == 'function' then
    _G.LOC = function(s)
        if type(s) ~= 'string' then
            return _oldLOC(s)
        end
        -- <LOC key> 标签串：解析 key 查简体字典（命中即返回简体）
        if string.sub(s, 1, 5) == '<LOC ' then
            local i = string.find(s, '>')
            if i then
                local key = string.sub(s, 6, i - 1)
                local tr = _BL_SIMPLIFIED[key]
                if tr ~= nil then
                    return tr
                end
            end
        end
        return _oldLOC(s)
    end
    pcall(function() WARN('[BrewLANZH] LOC wrapper installed (BrewLAN v0.899 zh-CN)') end)
end
