-- 替换全局 LOC: 所有模块裸调 LOC()/LOCF() 都经 _G, 这里统一翻译。
local _oldLOC = rawget(_G, 'LOC')
if _oldLOC and type(_oldLOC) == 'function' then
    _G.LOC = function(s)
        if type(s) ~= 'string' then
            return _oldLOC(s)
        end
        -- 1) <LOC key> 标签串: 解析 key 查 _4TH_LOC_TABLE
        if string.sub(s, 1, 5) == '<LOC ' then
            local i = string.find(s, '>')
            if i then
                local key = string.sub(s, 6, i - 1)
                local tr = _4TH_LOC_TABLE[key]
                if tr ~= nil then
                    return tr
                end
                -- 1b) key 未命中 LOC_TABLE 时, 回退查 ZH_MAP 的英文部分
                local eng = string.sub(s, i + 1)
                local tr1b = _4TH_ZH_MAP[eng]
                if tr1b ~= nil then
                    return tr1b
                end
            end
        end
        -- 2) 裸英文字串: 查 _4TH_ZH_MAP
        local tr2 = _4TH_ZH_MAP[s]
        if tr2 ~= nil then
            return tr2
        end
        -- 3) 其他: 原版处理
        return _oldLOC(s)
    end
    pcall(function() WARN('[4TH-ZH] LOC wrapper installed') end)
end
