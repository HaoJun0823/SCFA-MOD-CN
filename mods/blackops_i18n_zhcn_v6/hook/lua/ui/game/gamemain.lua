-- 替换全局 LOC: 所有模块裸调 LOC()/LOCF() 都经 _G, 这里统一翻译。
local _oldLOC = rawget(_G, 'LOC')
if _oldLOC and type(_oldLOC) == 'function' then
    _G.LOC = function(s)
        if type(s) ~= 'string' then
            return _oldLOC(s)
        end
        -- 1) <LOC key> 标签串: 解析 key 查 _BO_LOC_TABLE (loc_table 是 local 注入不了, 自建字典)
        if string.sub(s, 1, 5) == '<LOC ' then
            local i = string.find(s, '>')
            if i then
                local key = string.sub(s, 6, i - 1)
                local tr = _BO_LOC_TABLE[key]
                if tr ~= nil then
                    return tr
                end
            end
        end
        -- 2) 裸英文字串: 查 _BO_ZH_MAP
        local tr2 = _BO_ZH_MAP[s]
        if tr2 ~= nil then
            return tr2
        end
        -- 3) 其他: 原版处理
        return _oldLOC(s)
    end
    pcall(function() WARN('[BlackOpsZH] LOC wrapper installed (BlackOps V6 zh-CN)') end)
end